#!/bin/bash
# Step 3: build the new version's .env from the live one. Writes .env.upgraded, never touches .env.
#
# Usage (from the project directory): bash <upgrade-dir>/migrate-env.sh [--old .env.live] [--out .env.upgraded]
#
# Rules (nothing that works today changes):
#   - every key of the live .env is copied with its exact value (ENV_RENAMES "OLD:NEW" only renames the key)
#   - keys that are new in ENV_TEMPLATE are added with the template value, EXCEPT placeholders
#     (replace_*, changeme, <...>): left unset, so compose keeps the same default the old version used
#   - COMPOSE_PROJECT_NAME is pinned to the running project, so the same data volumes are used
#   - migrate_env_extra (upgrade.conf) can append computed keys
set -euo pipefail
source "$(dirname "$0")/_common.sh"

old=.env.live out=.env.upgraded
[[ -f "$old" ]] || old=.env
while [[ $# -gt 0 ]]; do
    case "$1" in
        --old) old="$2"; shift ;;
        --out) out="$2"; shift ;;
        *) sed -n '2,13p' "$0"; exit 1 ;;
    esac
    shift
done
[[ -f "$old" ]] || die "no $old"
[[ -e "$out" ]] && die "$out exists; remove it or pass --out"
[[ -f "$ENV_TEMPLATE" ]] || warn "no $ENV_TEMPLATE in the new version: only the live keys are carried over"

has() { grep -qE "^$1=" "$2"; }
placeholder() { [[ "$1" =~ (replace_|replace-me|changeme|change_me|your_|\<[a-z_ -]+\>) ]]; }

project="$(running_project)"; [[ -n "$project" ]] || project="$(basename "$PROJECT_ROOT")"
declare -A rename=(); for r in ${ENV_RENAMES[@]+"${ENV_RENAMES[@]}"}; do rename["${r%%:*}"]="${r#*:}"; done

added=() unset_ph=() renamed=()
umask 077
{
    echo "# Generated by upgrade/migrate-env.sh on $(date -u +%F) from $old."
    echo "# Values copied from the live .env are unchanged: they match the existing databases and data."
    echo
    has COMPOSE_PROJECT_NAME "$old" || { echo "# same data volumes as before (Docker prefixes volume names with the project)"; echo "COMPOSE_PROJECT_NAME=$project"; echo; }
    echo "# --- carried over from $old, unchanged ---"
    while IFS= read -r line; do
        key="${line%%=*}"
        if [[ -n "${rename[$key]:-}" ]]; then line="${rename[$key]}=${line#*=}"; renamed+=("$key->${rename[$key]}"); fi
        echo "$line"
    done < <(grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "$old")
    echo
    echo "# --- new in this version ---"
    if [[ -f "$ENV_TEMPLATE" ]]; then
        while IFS= read -r line; do
            key="${line%%=*}"
            has "$key" "$old" && continue
            for r in "${!rename[@]}"; do [[ "${rename[$r]}" == "$key" ]] && has "$r" "$old" && continue 2; done
            [[ "$key" == COMPOSE_PROJECT_NAME ]] && continue
            if placeholder "${line#*=}"; then
                echo "# $key: not set before either, so the built-in default stays in effect"; unset_ph+=("$key")
            else
                echo "${line%%[[:space:]]#*}"; added+=("$key")
            fi
        done < <(grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "$ENV_TEMPLATE" | awk -F= '!seen[$1]++')
    fi
} > "$out"
if declare -f migrate_env_extra >/dev/null; then migrate_env_extra "$old" "$out"; fi

say "wrote $out (0600)"
echo "  project:   $project"
echo "  renamed:   ${renamed[*]:-none}"
echo "  added:     ${added[*]:-none}"
echo "  left unset (old defaults stay): ${unset_ph[*]:-none}"
echo
echo "Review it:  diff <(grep -v '^#' $old | sort) <(grep -v '^#' $out | sort)"
echo "Then run:   bash $(dirname "$0")/preflight.sh <backup_dir>"
